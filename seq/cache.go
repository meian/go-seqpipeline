package seq

// Cache は入力を呼び出し時に全件評価し、その結果を繰り返し反復できる Seq を返す。
// Seq.Pipe に渡すか、関数として直接呼び出して使用する。
// 入力の順序と重複を保ち、nil は空の非 nil シーケンスとして扱う。
// 上流の副作用はこの呼び出し中に発生し、戻り値の反復では上流を再実行しない。
// 戻り値の反復を途中終了しても、次の反復は保存した先頭から開始する。
//
// 入力は有限である必要があり、保存には要素数に比例するメモリを使う。
// 無限入力は評価が完了しないため、必要なら Cache より前に Take を接続する。
// 要素は値として保存し、ポインター・スライス・map などの参照先はコピーしない。
// 保存後に元の要素を置き換えても結果は変わらないが、共有する参照先の変更は反映される。
// 入力の反復は戻る前に終了し、キャッシュが使われなくなると保存領域は回収可能になる。
// 戻り値は交互・並行に反復できるが、共有する参照先や下流のコールバックの同期は呼び出し側が担う。
func Cache[T any](src Seq[T]) Seq[T] {
	var values []T
	if src != nil {
		for v := range src {
			values = append(values, v)
		}
	}
	return func(yield func(T) bool) {
		for _, v := range values {
			if !yield(v) {
				return
			}
		}
	}
}

// Cache2 は入力を呼び出し時に全件評価し、その結果を繰り返し反復できる Seq2 を返す。
// Seq2.Pipe2 に渡すか、関数として直接呼び出して使用する。
// キーと値の組の順序と重複を保ち、キーに comparable を要求しない。
// nil は空の非 nil シーケンスとして扱う。
// 上流の副作用はこの呼び出し中に発生し、戻り値の反復では上流を再実行しない。
// 戻り値の反復を途中終了しても、次の反復は保存した先頭から開始する。
//
// 入力は有限である必要があり、保存には組数に比例するメモリを使う。
// 無限入力は評価が完了しないため、必要なら Cache2 より前に Take を接続する。
// キーと値は値として保存し、参照先はコピーしない。
// 保存後に元の組を置き換えても結果は変わらないが、共有する参照先の変更は反映される。
// 入力の反復は戻る前に終了し、キャッシュが使われなくなると保存領域は回収可能になる。
// 戻り値は交互・並行に反復できるが、共有する参照先や下流のコールバックの同期は呼び出し側が担う。
func Cache2[K, V any](src Seq2[K, V]) Seq2[K, V] {
	type pair struct {
		key   K
		value V
	}
	var pairs []pair
	if src != nil {
		for k, v := range src {
			pairs = append(pairs, pair{key: k, value: v})
		}
	}
	return func(yield func(K, V) bool) {
		for _, p := range pairs {
			if !yield(p.key, p.value) {
				return
			}
		}
	}
}
